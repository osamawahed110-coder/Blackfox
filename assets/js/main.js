document.addEventListener('click', function(e){
  var btn = e.target.closest('.btn-cta-gold,.btn-cta-outline,.btn-p,.btn-quote');
  if(!btn) return;
  var r = document.createElement('span');
  var rect = btn.getBoundingClientRect();
  var size = Math.max(rect.width, rect.height) * 1.6;
  var x = e.clientX - rect.left - size/2;
  var y = e.clientY - rect.top - size/2;
  r.style.cssText = 'position:absolute;border-radius:50%;pointer-events:none;'
    +'width:'+size+'px;height:'+size+'px;'
    +'left:'+x+'px;top:'+y+'px;'
    +'background:rgba(255,255,255,.28);'
    +'transform:scale(0);opacity:1;'
    +'animation:ripple .55s ease forwards;z-index:10';
  btn.style.overflow = 'hidden';
  btn.appendChild(r);
  r.addEventListener('animationend', function(){ r.remove(); });
});

// Smooth scroll for all internal links — works on file:// and http://
document.addEventListener('click', function(e){
  var a = e.target.closest('a');
  if(!a) return;
  var href = a.getAttribute('href');
  if(!href || !href.startsWith('#')) return;
  var id = href.slice(1);
  if(!id) return;
  var target = document.getElementById(id);
  if(!target) return;
  e.preventDefault();
  e.stopPropagation();
  target.scrollIntoView({behavior:'smooth',block:'start'});
  // Close mobile menu if open
  var mob = g('mob-menu');
  if(mob) mob.style.display = 'none';
}, true); // capture phase — fires before any inline onclick

