// ── SCROLL ANIMATIONS ─────────────────────────────────────────────────────
(function(){
  var obs = new IntersectionObserver(function(entries){
    entries.forEach(function(entry){
      if(entry.isIntersecting){
        var el = entry.target;
        el.classList.add('visible');
        // Stagger children in grid/list containers
        var children = el.querySelectorAll('.sv-card,.wy-card,.cl-tile,.st-card,.pr-cat,.val-c,.ab-card');
        children.forEach(function(child,i){
          child.style.animationDelay = (0.04 + i * 0.09) + 's';
          child.classList.add('anim-scale');
          setTimeout(function(){ child.classList.add('visible'); }, 40 + i * 90);
        });
      }
    });
  }, {threshold: 0.08, rootMargin: '0px 0px -40px 0px'});

  function observeAll(){
    var els = document.querySelectorAll('.anim-fadeup,.anim-fadein,.anim-left,.anim-right,.anim-scale');
    els.forEach(function(el){ obs.observe(el); });
    
    // H-stats special
    var stats = document.querySelector('.h-stats');
    if(stats){
      var statsObs = new IntersectionObserver(function(entries){
        if(entries[0].isIntersecting) stats.classList.add('visible');
      }, {threshold:0.3});
      statsObs.observe(stats);
    }
  }

  // Run after render populates the DOM
  setTimeout(observeAll, 100);
  
  // Also re-run on lang change
  var origRender = window.render || function(){};
  var origSetLang = window.setLang;
  window.setLang = function(l){
    origSetLang(l);
    setTimeout(observeAll, 150);
  };
})();
