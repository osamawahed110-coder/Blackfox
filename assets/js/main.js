function loadImg(input){
  if(!input.files[0]) return;
  var reader = new FileReader();
  var slot = input.closest('.md-slot');
  reader.onload = function(e){
    slot.querySelector('img').src = e.target.result;
    slot.querySelector('img').style.display = 'block';
    slot.querySelector('.md-ph').style.display = 'none';
  };
  reader.readAsDataURL(input.files[0]);
}

function embedVid(){
  var url = g('vid-inp').value.trim();
  if(!url) return;
  var embed = '';
  var yt = url.match(/(?:youtu\.be\/|youtube\.com\/(?:watch\?v=|embed\/))([-\w]+)/);
  var vi = url.match(/vimeo\.com\/(\d+)/);
  if(yt) embed = 'https://www.youtube.com/embed/' + yt[1];
  else if(vi) embed = 'https://player.vimeo.com/video/' + vi[1];
  else embed = url;
  g('vid-frame').innerHTML = '<iframe src="' + embed + '" allow="autoplay;encrypted-media" allowfullscreen></iframe>';
}

